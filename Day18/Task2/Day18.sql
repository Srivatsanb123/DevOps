CREATE WAREHOUSE IF NOT EXISTS SRIVATSAN_RETAIL_WH
WAREHOUSE_SIZE = 'XSMALL'
AUTO_SUSPEND = 60
AUTO_RESUME = TRUE
INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS SRIVATSAN_RETAIL_DB;

CREATE SCHEMA IF NOT EXISTS SRIVATSAN_RETAIL_DB.RAW;

USE WAREHOUSE SRIVATSAN_RETAIL_WH;

USE DATABASE SRIVATSAN_RETAIL_DB;

USE SCHEMA RAW;

CREATE TABLE IF NOT EXISTS RETAIL_SALES (
    ORDER_ID VARCHAR(20),
    CUSTOMER_ID VARCHAR(20),
    ORDER_DATE DATE,
    CITY VARCHAR(50),
    REGION VARCHAR(20),
    PRODUCT_CATEGORY VARCHAR(50),
    PRODUCT VARCHAR(50),
    QUANTITY NUMBER(10,0),
    UNIT_PRICE NUMBER(12,2),
    REVENUE NUMBER(12,2),
    SALES_CHANNEL VARCHAR(30),
    PAYMENT_METHOD VARCHAR(30)
);

CREATE OR REPLACE FILE FORMAT RETAIL_CSV_FORMAT
TYPE = CSV
FIELD_DELIMITER = ','
SKIP_HEADER = 1
FIELD_OPTIONALLY_ENCLOSED_BY = '"'
DATE_FORMAT = 'YYYY-MM-DD'
EMPTY_FIELD_AS_NULL = TRUE
TRIM_SPACE = TRUE;

CREATE OR REPLACE STAGE RETAIL_SALES_STAGE
FILE_FORMAT = RETAIL_CSV_FORMAT;

LIST @RETAIL_SALES_STAGE;

COPY INTO RETAIL_SALES
FROM @RETAIL_SALES_STAGE
FILE_FORMAT = (FORMAT_NAME = RETAIL_CSV_FORMAT)
ON_ERROR = 'ABORT_STATEMENT';
SELECT * FROM RETAIL_SALES;