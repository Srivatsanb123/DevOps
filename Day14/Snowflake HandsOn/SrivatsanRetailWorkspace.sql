SELECT CURRENT_USER() AS USER_NAME, CURRENT_ROLE() AS ACTIVE_ROLE, CURRENT_WAREHOUSE() AS ACTIVE_WAREHOUSE, CURRENT_DATABASE() AS ACTIVE_DATABASE, CURRENT_SCHEMA() AS ACTIVE_SCHEMA;

CREATE DATABASE IF NOT EXISTS RETAIL_DB;

SHOW DATABASES LIKE 'RETAIL_DB';

DROP DATABASE RETAIL_DB;

SHOW DATABASES LIKE 'RETAIL_DB';

CREATE DATABASE IF NOT EXISTS SRIVATSAN_RETAIL_DB;

SHOW DATABASES LIKE 'SRIVATSAN_RETAIL_DB';

CREATE SCHEMA IF NOT EXISTS RAW;

USE SCHEMA SRIVATSAN_RETAIL_DB.RAW;

SHOW SCHEMAS IN DATABASE SRIVATSAN_RETAIL_DB;

CREATE WAREHOUSE IF NOT EXISTS SRIVATSAN_RETAIL_WH
WAREHOUSE_SIZE = 'XSMALL'
AUTO_SUSPEND = 60
AUTO_RESUME = TRUE
INITIALLY_SUSPENDED = TRUE;

USE WAREHOUSE SRIVATSAN_RETAIL_WH;
SHOW WAREHOUSES LIKE 'SRIVATSAN_RETAIL_WH';
CREATE TABLE IF NOT EXISTS SALES(
ORDER_ID NUMBER(10,0),
PRODUCT VARCHAR(100),
QUANTITY NUMBER(10,0),
UNIT_PRICE NUMBER(12,2),
CITY VARCHAR(100)
);
SHOW TABLES LIKE 'SALES' IN SCHEMA SRIVATSAN_RETAIL_DB.RAW;

DESCRIBE TABLE SRIVATSAN_RETAIL_DB.RAW.SALES;

CREATE FILE FORMAT IF NOT EXISTS SRIVATSAN_RETAIL_CSV_FORMAT
TYPE = CSV
SKIP_HEADER=1
FIELD_OPTIONALLY_ENCLOSED_BY='"'
EMPTY_FIELD_AS_NULL=TRUE;

SHOW FILE FORMATS IN SCHEMA SRIVATSAN_RETAIL_DB.RAW;

CREATE STAGE IF NOT EXISTS SRIVATSAN_RETAIL_STAGE FILE_FORMAT = SRIVATSAN_RETAIL_CSV_FORMAT;

SHOW STAGES IN SCHEMA SRIVATSAN_RETAIL_DB.RAW;

LIST@SRIVATSAN_RETAIL_DB.RAW.SRIVATSAN_RETAIL_STAGE;

COPY INTO SRIVATSAN_RETAIL_DB.RAW.SALES
FROM @SRIVATSAN_RETAIL_DB.RAW.SRIVATSAN_RETAIL_STAGE
FILE_FORMAT=(
FORMAT_NAME='SRIVATSAN_RETAIL_DB.RAW.SRIVATSAN_RETAIL_CSV_FORMAT'
)
ON_ERROR='ABORT_STATEMENT';

SELECT COUNT(*) AS TOTAL_RECORDS FROM SRIVATSAN_RETAIL_DB.RAW.SALES;

SELECT * FROM SRIVATSAN_RETAIL_DB.RAW.SALES ORDER BY ORDER_ID;

SELECT ORDER_ID, COUNT(*) AS RECORD_COUNT FROM SRIVATSAN_RETAIL_DB.RAW.SALES GROUP BY ORDER_ID HAVING COUNT(*)>1;

DROP DATABASE IF EXISTS SRIVATSAN_RETAIL_DB;

DROP WAREHOUSE IF EXISTS SRIVATSAN_RETAIL_WH;