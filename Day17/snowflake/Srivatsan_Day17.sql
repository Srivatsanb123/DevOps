COPY INTO SRIVATSAN_RETAIL_DB.RAW.PRODUCTS
FROM @SRIVATSAN_RETAIL_DB.RAW.SRIVATSAN_RETAIL_STAGE
FILES = ('srivatsan_products.csv')
FILE_FORMAT = (
    FORMAT_NAME = 'SRIVATSAN_RETAIL_DB.RAW.SRIVATSAN_RETAIL_CSV_FORMAT'
)
ON_ERROR = 'ABORT_STATEMENT';

CREATE OR REPLACE TABLE SRIVATSAN_RETAIL_DB.RAW.CLEAN_SALES AS
SELECT
    ORDER_ID,
    CUSTOMER_ID,
    PRODUCT_ID,
    QUANTITY,
    UNIT_PRICE,
    UPPER(TRIM(CITY)) AS CITY,
    QUANTITY * UNIT_PRICE AS TOTAL_AMOUNT
FROM SRIVATSAN_RETAIL_DB.RAW.SALES;
SELECT * FROM SRIVATSAN_RETAIL_DB.RAW.CLEAN_SALES;

CREATE OR REPLACE TABLE SRIVATSAN_RETAIL_DB.RAW.CLEAN_CUSTOMERS AS
SELECT
    CUSTOMER_ID,
    COALESCE(NULLIF(TRIM(CUSTOMER_NAME), ''), 'UNKNOWN') AS CUSTOMER_NAME,
    LOWER(TRIM(EMAIL)) AS EMAIL,
    TRIM(PHONE) AS PHONE,
    UPPER(TRIM(CITY)) AS CITY
FROM SRIVATSAN_RETAIL_DB.RAW.CUSTOMERS;

SELECT * FROM SRIVATSAN_RETAIL_DB.RAW.CLEAN_CUSTOMERS;

CREATE OR REPLACE TABLE SRIVATSAN_RETAIL_DB.RAW.CLEAN_PRODUCTS AS
SELECT
    PRODUCT_ID,
    COALESCE(NULLIF(TRIM(PRODUCT_NAME), ''), 'UNKNOWN') AS PRODUCT_NAME,
    UPPER(TRIM(CATEGORY)) AS CATEGORY,
    UNIT_PRICE,
    STOCK_QUANTITY
FROM SRIVATSAN_RETAIL_DB.RAW.PRODUCTS;

SELECT * FROM SRIVATSAN_RETAIL_DB.RAW.CLEAN_PRODUCTS;


SELECT *
FROM SRIVATSAN_RETAIL_DB.RAW.CLEAN_SALES
ORDER BY ORDER_ID;

SELECT
    ORDER_ID,
    CUSTOMER_ID,
    PRODUCT_ID,
    QUANTITY,
    UNIT_PRICE,
    TOTAL_AMOUNT,
    CITY AS ORDER_LOCATION
FROM SRIVATSAN_RETAIL_DB.RAW.CLEAN_SALES
ORDER BY ORDER_ID;

SELECT
    P.PRODUCT_ID,
    P.PRODUCT_NAME,
    SUM(S.QUANTITY) AS TOTAL_QUANTITY_SOLD,
    SUM(S.TOTAL_AMOUNT) AS TOTAL_SALES
FROM SRIVATSAN_RETAIL_DB.RAW.CLEAN_SALES S
INNER JOIN SRIVATSAN_RETAIL_DB.RAW.CLEAN_PRODUCTS P
    ON S.PRODUCT_ID = P.PRODUCT_ID
GROUP BY
    P.PRODUCT_ID,
    P.PRODUCT_NAME
ORDER BY TOTAL_SALES DESC;

SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    C.CITY,
    SUM(S.TOTAL_AMOUNT) AS TOTAL_CUSTOMER_SPEND
FROM SRIVATSAN_RETAIL_DB.RAW.CLEAN_SALES S
INNER JOIN SRIVATSAN_RETAIL_DB.RAW.CLEAN_CUSTOMERS C
    ON S.CUSTOMER_ID = C.CUSTOMER_ID
GROUP BY
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    C.CITY
ORDER BY TOTAL_CUSTOMER_SPEND DESC;

SELECT
    PRODUCT_ID,
    SUM(TOTAL_AMOUNT) AS TOTAL_SALES
FROM SRIVATSAN_RETAIL_DB.RAW.CLEAN_SALES
GROUP BY PRODUCT_ID
HAVING SUM(TOTAL_AMOUNT) > 5000
ORDER BY TOTAL_SALES DESC;

DROP TABLE IF EXISTS SRIVATSAN_RETAIL_DB.RAW.CLEAN_SALES;

DROP TABLE IF EXISTS SRIVATSAN_RETAIL_DB.RAW.CLEAN_CUSTOMERS;

