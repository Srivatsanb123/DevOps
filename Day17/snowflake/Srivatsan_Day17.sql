SELECT
    CURRENT_USER() AS USER_NAME,
    CURRENT_ROLE() AS ACTIVE_ROLE,
    CURRENT_WAREHOUSE() AS ACTIVE_WAREHOUSE,
    CURRENT_DATABASE() AS ACTIVE_DATABASE,
    CURRENT_SCHEMA() AS ACTIVE_SCHEMA;
CREATE DATABASE IF NOT EXISTS SRIVATSAN_RETAIL_DB;
SHOW DATABASES LIKE 'SRIVATSAN_RETAIL_DB';
CREATE SCHEMA IF NOT EXISTS SRIVATSAN_RETAIL_DB.RAW;
USE SCHEMA SRIVATSAN_RETAIL_DB.RAW;
SHOW SCHEMAS IN DATABASE SRIVATSAN_RETAIL_DB;
CREATE WAREHOUSE IF NOT EXISTS SRIVATSAN_RETAIL_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

USE WAREHOUSE SRIVATSAN_RETAIL_WH;

CREATE FILE FORMAT IF NOT EXISTS SRIVATSAN_RETAIL_CSV_FORMAT
    TYPE = CSV
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    EMPTY_FIELD_AS_NULL = TRUE
    TRIM_SPACE = FALSE;
SHOW FILE FORMATS IN SCHEMA SRIVATSAN_RETAIL_DB.RAW;
CREATE STAGE IF NOT EXISTS SRIVATSAN_RETAIL_STAGE
    FILE_FORMAT = SRIVATSAN_RETAIL_CSV_FORMAT;
SHOW STAGES IN SCHEMA SRIVATSAN_RETAIL_DB.RAW;
LIST @SRIVATSAN_RETAIL_DB.RAW.SRIVATSAN_RETAIL_STAGE;

CREATE TABLE IF NOT EXISTS SRIVATSAN_RETAIL_DB.RAW.SALES (
    ORDER_ID NUMBER(10,0),
    CUSTOMER_ID NUMBER(10,0),
    PRODUCT_ID NUMBER(10,0),
    QUANTITY NUMBER(10,0),
    UNIT_PRICE NUMBER(12,2),
    CITY VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS SRIVATSAN_RETAIL_DB.RAW.CUSTOMERS (
    CUSTOMER_ID NUMBER(10,0),
    CUSTOMER_NAME VARCHAR(100),
    EMAIL VARCHAR(150),
    PHONE VARCHAR(20),
    CITY VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS SRIVATSAN_RETAIL_DB.RAW.PRODUCTS (
    PRODUCT_ID NUMBER(10,0),
    PRODUCT_NAME VARCHAR(100),
    CATEGORY VARCHAR(100),
    UNIT_PRICE NUMBER(12,2),
    STOCK_QUANTITY NUMBER(10,0)
);

SHOW TABLES IN SCHEMA SRIVATSAN_RETAIL_DB.RAW;

DESCRIBE TABLE SRIVATSAN_RETAIL_DB.RAW.SALES;

DESCRIBE TABLE SRIVATSAN_RETAIL_DB.RAW.CUSTOMERS;

DESCRIBE TABLE SRIVATSAN_RETAIL_DB.RAW.PRODUCTS;

