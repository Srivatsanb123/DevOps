SELECT
    CURRENT_USER(),
    CURRENT_ROLE(),
    CURRENT_WAREHOUSE(),
    CURRENT_DATABASE(),
    CURRENT_SCHEMA();

CREATE DATABASE IF NOT EXISTS SRIVATSAN_FOOD_DELIVERY_DB;

SHOW DATABASES LIKE 'SRIVATSAN_FOOD_DELIVERY_DB';

CREATE SCHEMA IF NOT EXISTS SRIVATSAN_FOOD_DELIVERY_DB.RAW;

SHOW SCHEMAS IN DATABASE SRIVATSAN_FOOD_DELIVERY_DB;

USE SCHEMA SRIVATSAN_FOOD_DELIVERY_DB.RAW;


CREATE WAREHOUSE IF NOT EXISTS SRIVATSAN_FOOD_DELIVERY_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

SHOW WAREHOUSES LIKE 'SRIVATSAN_FOOD_DELIVERY_WH';

USE WAREHOUSE SRIVATSAN_FOOD_DELIVERY_WH;

CREATE TABLE IF NOT EXISTS FOOD_DELIVERY_ORDERS (
    ORDER_ID NUMBER(10,0),
    CUSTOMER_NAME VARCHAR(100),
    RESTAURANT VARCHAR(100),
    ORDER_AMOUNT NUMBER(10,2),
    DELIVERY_CITY VARCHAR(100),
    PAYMENT_METHOD VARCHAR(30),
    ORDER_STATUS VARCHAR(40)
);

SHOW TABLES LIKE 'FOOD_DELIVERY_ORDERS' IN SCHEMA SRIVATSAN_FOOD_DELIVERY_DB.RAW;

DESCRIBE TABLE FOOD_DELIVERY_ORDERS;

CREATE FILE FORMAT IF NOT EXISTS SRIVATSAN_FOOD_DELIVERY_CSV_FORMAT
    TYPE = CSV
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    EMPTY_FIELD_AS_NULL = TRUE
    TRIM_SPACE = TRUE;


SHOW FILE FORMATS IN SCHEMA SRIVATSAN_FOOD_DELIVERY_DB.RAW;

CREATE STAGE IF NOT EXISTS SRIVATSAN_FOOD_DELIVERY_STAGE
    FILE_FORMAT = SRIVATSAN_FOOD_DELIVERY_CSV_FORMAT;

SHOW STAGES IN SCHEMA SRIVATSAN_FOOD_DELIVERY_DB.RAW;

LIST @SRIVATSAN_FOOD_DELIVERY_STAGE;

COPY INTO FOOD_DELIVERY_ORDERS
FROM @SRIVATSAN_FOOD_DELIVERY_STAGE
FILE_FORMAT = (FORMAT_NAME = 'SRIVATSAN_FOOD_DELIVERY_CSV_FORMAT')
ON_ERROR = 'ABORT_STATEMENT';

SELECT COUNT(*) FROM FOOD_DELIVERY_ORDERS;

SELECT * FROM FOOD_DELIVERY_ORDERS ORDER BY ORDER_ID;

SELECT ORDER_STATUS, COUNT(*) AS ORDER_COUNT
FROM FOOD_DELIVERY_ORDERS
GROUP BY ORDER_STATUS
ORDER BY ORDER_COUNT DESC;

SELECT DELIVERY_CITY, COUNT(*) AS TOTAL_ORDERS
FROM FOOD_DELIVERY_ORDERS
GROUP BY DELIVERY_CITY
ORDER BY TOTAL_ORDERS DESC;

DROP DATABASE IF EXISTS SRIVATSAN_FOOD_DELIVERY_DB;

DROP WAREHOUSE IF EXISTS SRIVATSAN_FOOD_DELIVERY_WH;